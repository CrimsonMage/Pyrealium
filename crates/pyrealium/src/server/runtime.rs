//! The running server's long-lived state: everything `run_auth_mode` sets up before its
//! loop and the loop reads or changes, except the peers (borrowed per datagram) and the
//! receive buffer.
use super::*;

/// Fields are declared in the reverse of the order `run_auth_mode` creates them, so they
/// drop in the order its locals did (the Store's final save among them).
pub(super) struct Server {
    /// This loop pass's clock (`Instant::now()` and milliseconds since `start`).
    pub(super) now: Instant,
    pub(super) now_ms: u64,
    pub(super) next_resource_cleanup: u64,
    pub(super) admin: Option<crate::admin::Handle>,
    pub(super) diagnosed_queues: BTreeSet<(u16, u32)>,
    pub(super) diagnosed_packet_errors: BTreeSet<String>,
    pub(super) diagnosed_application_errors: BTreeSet<String>,
    pub(super) diagnosed_events: BTreeSet<u32>,
    pub(super) next_gun_publish: u64,
    pub(super) next_checkpoint: u64,
    pub(super) next_stop_check: u64,
    pub(super) next_untraining_tick: u64,
    pub(super) next_report: u64,
    pub(super) counters: Counters,
    pub(super) generation: u64,
    pub(super) login_limits: crate::auth::RateLimit,
    pub(super) next_group_refresh: u64,
    pub(super) group_cache: BTreeMap<u64, crate::groups::Member>,
    pub(super) trades: crate::trade::Runtime,
    pub(super) groups: crate::groups::Runtime,
    pub(super) next_offer: u64,
    pub(super) failed_peers: BTreeSet<SocketAddr>,
    pub(super) abilities: Option<crate::abilities::Runtime>,
    pub(super) training_quest_enabled: bool,
    pub(super) scene: crate::scene::Scene,
    pub(super) active_characters: BTreeMap<u64, SocketAddr>,
    pub(super) world_clock: crate::clock::WorldClock,
    pub(super) start: Instant,
    pub(super) secondary: UdpSocket,
    pub(super) primary: UdpSocket,
    pub(super) examination_names: crate::examination::Names,
    pub(super) portal_contacts: Option<crate::portals::Contacts>,
    pub(super) portal_routes: crate::portals::Routes,
    pub(super) encounters: Option<crate::encounters::Encounters>,
    pub(super) corpse_loot: crate::loot::Loot,
    pub(super) projectiles: crate::projectiles::Projectiles,
    pub(super) initial_ui: Option<Vec<u8>>,
    pub(super) shelter_gameplay: bool,
    pub(super) starter_equipment: bool,
    pub(super) quest_gameplay: bool,
    pub(super) trade_assets: Option<crate::tradeskills::Assets>,
    pub(super) money_coin: Option<crate::money::Coin>,
    pub(super) merchant_catalog: Option<crate::merchants::Catalog>,
    pub(super) inventory_metadata: BTreeMap<u32, Option<crate::inventory_request::Metadata>>,
    pub(super) store: Store,
    pub(super) bootstrap: Option<crate::bootstrap::Bootstrap>,
    pub(super) map_landscape: Option<crate::map_travel::Landscape>,
    pub(super) auth_data: Option<crate::db::Connection>,
    pub(super) local_accounts: bool,
    pub(super) config: Config,
}
